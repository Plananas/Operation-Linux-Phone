#!/usr/bin/env python3
"""Turn the TREND OS boot frame (480x800 RGBX, from `trendos.py --boot-frame`) into a C header
for the kernel: only the bounding box of non-black pixels is stored; the rest is cleared.
Usage: mklogo_h.py logo.rgbx trendos_logo.h"""
import sys

W, H = 480, 800
src, out = sys.argv[1:]
d = open(src, "rb").read()
assert len(d) == W * H * 4, len(d)


def lit(x, y):
    o = (y * W + x) * 4
    return d[o] | d[o + 1] | d[o + 2]


rows = [y for y in range(H) if any(lit(x, y) for x in range(W))]
cols = [x for x in range(W) if any(lit(x, y) for y in rows)]
x0, x1, y0, y1 = min(cols), max(cols) + 1, min(rows), max(rows) + 1
with open(out, "w") as f:
    f.write(f"/* generated by tools/kernel/mklogo_h.py from the TREND OS boot frame */\n"
            f"#define TRENDOS_LOGO_X {x0}\n#define TRENDOS_LOGO_Y {y0}\n"
            f"#define TRENDOS_LOGO_W {x1 - x0}\n#define TRENDOS_LOGO_H {y1 - y0}\n"
            f"static const uint32_t trendos_logo[] __initconst = {{\n")
    for y in range(y0, y1):
        o = (y * W + x0) * 4
        row = d[o:o + (x1 - x0) * 4]
        f.write(",".join(f"0x{int.from_bytes(row[i:i + 4], 'little'):x}" for i in range(0, len(row), 4)) + ",\n")
    f.write("};\n")
print(f"{out}: box x {x0}..{x1} y {y0}..{y1} ({(x1 - x0) * (y1 - y0) * 4 // 1024} KiB)")
